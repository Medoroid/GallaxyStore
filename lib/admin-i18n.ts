const dictionaries: Record<"en" | "ar", Record<string, string>> = { en, ar };

/**
 * Translation hook for admin pages. Reads the SAME locale as the storefront
 * (LanguageProvider), so choosing Arabic also sets `dir="rtl"` document-wide.
 */
export function useAdminT() {
  const { locale, setLocale } = useLanguage();
  const dict = dictionaries[locale === "ar" ? "ar" : "en"];
  const t = (key: string): string => dict[key] ?? en[key as AdminKey] ?? key;
  return { t, locale, setLocale } as const;
}
