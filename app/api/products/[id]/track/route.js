import { createClient } from "@supabase/supabase-js";
import { randomUUID } from "crypto";
import { logger } from "@/lib/logger";
import { checkRateLimitAsync, getClientIp } from "@/lib/rate-limit";

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

// POST - Track a product view
export async function POST(request, { params }) {
  try {
    const { id: product_id } = await params;
    if (!UUID_RE.test(product_id)) {
      return Response.json({ success: false, message: "Invalid product id" }, { status: 400 });
    }

    // Public write: bound view-count pollution per IP. Fail closed so a Redis
    // outage cannot remove the rate limit on this unauthenticated endpoint.
    const { allowed } = await checkRateLimitAsync(`product-track:${getClientIp(request)}`, {
      maxRequests: 60,
      windowMs: 60_000,
      failureMode: "fail_closed",
    });
    if (!allowed) {
      return Response.json(
        { success: false, message: "Too many requests" },
        { status: 429 }
      );
    }

    const authHeader = request.headers.get("authorization");
    let SupabaseClient = createClient(
      process.env.NEXT_PUBLIC_SUPABASE_URL,
      process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY
    );
    let session_token = null;
    let user = null;

    if (authHeader) {
      const token = authHeader.replace("Bearer ", "");
      // The RPC reads auth.uid(); the JWT must be attached to the client that
      // invokes it, not only used for the getUser() validation call.
      SupabaseClient = createClient(
        process.env.NEXT_PUBLIC_SUPABASE_URL,
        process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY,
        { global: { headers: { Authorization: `Bearer ${token}` } } }
      );
      const { data: { user: authUser } } = await SupabaseClient.auth.getUser(token);
      user = authUser;
    }

    if (!user) {
      // Guest: the session token is a UUID generated by lib/cartService.
      const body = await request.json().catch(() => ({}));
      session_token = body.session_token || randomUUID();
      if (!UUID_RE.test(String(session_token))) {
        return Response.json({ success: false, message: "Invalid session token" }, { status: 400 });
      }
    }

    const { error } = await SupabaseClient.rpc("track_product_view", {
      p_product_id: product_id,
      p_session_token: session_token,
    });

    if (error) throw error;
    return Response.json({ success: true, session_token });
  } catch (error) {
    logger.error("[Track Product View Error]", error);
    return Response.json(
      { success: false, message: "Failed to track view" },
      { status: 500 }
    );
  }
}
