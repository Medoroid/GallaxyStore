import { checkRateLimitAsync, getClientIp } from "@/lib/rate-limit";
import { handleApiError } from "@/lib/api-errors";
import { requireUser } from "@/lib/creator/api";
import { resolveDesignTitle } from "@/lib/design-studio/design-input";
import {
  DESIGN_UPLOAD_BUCKET,
  migrationGuard,
  prepareArtwork,
  readUpload,
  uploadFailure,
  artworkStoragePath,
} from "@/lib/design-studio/server";

export const runtime = "nodejs";

const DEFAULT_PER_PAGE = 12;
const MAX_PER_PAGE = 24;

const DESIGN_LIST_COLUMNS =
  "id, title, slug, description, status, is_public, rejection_reason, created_at, updated_at";

const FILE_COLUMNS =
  "id, storage_path, original_filename, file_format, mime_type, file_size_bytes, width_px, height_px, dpi, color_mode, has_transparent_background, is_primary, scan_status";

function clampInt(raw, fallback, min, max) {
  const value = Number.parseInt(String(raw ?? ""), 10);
  if (!Number.isFinite(value)) return fallback;
  return Math.min(Math.max(value, min), max);
}

// GET — the caller's own designs (RLS scopes every row to auth.uid()).
// Pagination is exact-count driven so the grid can render honest page controls.
export async function GET(request) {
  try {
    const auth = await requireUser(request);
    if (!auth.ok) return auth.response;

    const url = new URL(request.url);
    const page = clampInt(url.searchParams.get("page"), 1, 1, 10_000);
    const perPage = clampInt(url.searchParams.get("per_page"), DEFAULT_PER_PAGE, 1, MAX_PER_PAGE);
    const from = (page - 1) * perPage;

    const { data, error, count } = await auth.client
      .from("user_designs")
      .select(DESIGN_LIST_COLUMNS, { count: "exact" })
      .eq("owner_id", auth.user.id)
      .is("deleted_at", null)
      .order("updated_at", { ascending: false })
      .range(from, from + perPage - 1);

    if (error) throw error;

    const designs = data ?? [];
    let versionsByDesign = new Map();

    if (designs.length > 0) {
      const ids = designs.map((design) => design.id);
      const { data: versions, error: versionsError } = await auth.client
        .from("design_versions")
        .select(`id, design_id, version_number, status, is_current, created_at, updated_at, design_files(${FILE_COLUMNS})`)
        .in("design_id", ids)
        .eq("is_current", true);

      if (versionsError) throw versionsError;

      versionsByDesign = new Map(
        (versions ?? []).map((version) => [
          version.design_id,
          {
            id: version.id,
            version_number: version.version_number,
            status: version.status,
            created_at: version.created_at,
            updated_at: version.updated_at,
            file:
              (version.design_files ?? []).find((file) => file.is_primary) ??
              (version.design_files ?? [])[0] ??
              null,
          },
        ])
      );
    }

    return Response.json({
      success: true,
      designs: designs.map((design) => ({
        ...design,
        version: versionsByDesign.get(design.id) ?? null,
      })),
      page,
      per_page: perPage,
      total: count ?? designs.length,
      has_more: (count ?? 0) > from + designs.length,
    });
  } catch (error) {
    return handleApiError(error, "Designs GET", "Could not load your designs.");
  }
}

// POST — create a design from an uploaded artwork (multipart: "file" + optional "title").
//
// Writes run under the CALLER's JWT: user_designs/design_versions/design_files
// have owner-write RLS with `with_check` ownership, so the database enforces
// who created what even if this handler got something wrong. Slug and version
// numbers are generated by DB triggers; only sanitized SVG bytes are stored.
export async function POST(request) {
  try {
    const ip = getClientIp(request);
    const { allowed } = await checkRateLimitAsync(`designs-create:${ip}`, {
      maxRequests: 10,
      failureMode: "fail_closed",
    });
    if (!allowed) {
      return Response.json(
        { success: false, message: "Too many uploads. Please wait a minute." },
        { status: 429 }
      );
    }

    const auth = await requireUser(request);
    if (!auth.ok) return auth.response;

    // Fail fast (before any side effects) when the studio migration is missing.
    const guard = await migrationGuard(auth.client, "designs.create");
    if (guard.missing) return guard.response;

    const upload = await readUpload(request, "file");
    if (!upload.ok) return upload.response;

    const title = resolveDesignTitle(upload.form.get("title"), upload.file.name);

    const prepared = prepareArtwork(upload.bytes, {
      filename: upload.file.name,
      mimeType: upload.file.type,
    });
    if (!prepared.ok) return uploadFailure(prepared);

    const designId = crypto.randomUUID();
    const storagePath = artworkStoragePath(auth.user.id, designId, prepared.format);

    // 1) Storage first — a failure here leaves no database rows behind.
    const { error: uploadError } = await auth.client.storage
      .from(DESIGN_UPLOAD_BUCKET)
      .upload(storagePath, Buffer.from(prepared.storeBytes), {
        contentType: prepared.contentType,
        upsert: false,
      });
    if (uploadError) {
      return Response.json(
        {
          success: false,
          code: "storage_rejected",
          message: `Storage rejected the file: ${uploadError.message}`,
        },
        { status: 400 }
      );
    }

    const cleanupStorage = async () => {
      try {
        await auth.client.storage.from(DESIGN_UPLOAD_BUCKET).remove([storagePath]);
      } catch {
        // best effort — never masks the original failure
      }
    };

    // 2) Design row. slug is generated + uniquified by the DB trigger.
    const { data: design, error: designError } = await auth.client
      .from("user_designs")
      .insert({
        owner_id: auth.user.id,
        title,
        status: "draft",
        is_public: false,
      })
      .select("id, title, slug, description, status, is_public, created_at, updated_at")
      .single();

    if (designError) {
      await cleanupStorage();
      throw designError;
    }

    // 3) Version 1 — the trigger assigns version_number and flips is_current.
    const { data: version, error: versionError } = await auth.client
      .from("design_versions")
      .insert({
        design_id: design.id,
        status: "draft",
        is_current: true,
      })
      .select("id, version_number, status, is_current, created_at")
      .single();

    if (versionError) {
      // No hard DELETE is allowed for creators (RLS) — soft-delete instead.
      await auth.client.from("user_designs").update({ deleted_at: new Date().toISOString() }).eq("id", design.id);
      await cleanupStorage();
      throw versionError;
    }

    // 4) File row — dimensions/DPI/transparency come from parsed headers.
    const { data: fileRow, error: fileError } = await auth.client
      .from("design_files")
      .insert({
        version_id: version.id,
        file_format: prepared.format,
        storage_path: storagePath,
        original_filename: String(upload.file.name ?? "").slice(0, 255) || null,
        mime_type: prepared.contentType,
        file_size_bytes: prepared.storeBytes.length,
        width_px: prepared.widthPx,
        height_px: prepared.heightPx,
        dpi: prepared.dpi,
        color_mode: prepared.colorMode,
        has_transparent_background: prepared.hasTransparency,
        checksum_sha256: prepared.sha256,
        is_primary: true,
        scan_status: "pending",
      })
      .select(
        "id, storage_path, original_filename, file_format, mime_type, file_size_bytes, width_px, height_px, dpi, color_mode, has_transparent_background, is_primary, scan_status"
      )
      .single();

    if (fileError) {
      await auth.client.from("design_versions").delete().eq("id", version.id);
      await auth.client.from("user_designs").update({ deleted_at: new Date().toISOString() }).eq("id", design.id);
      await cleanupStorage();
      throw fileError;
    }

    return Response.json(
      {
        success: true,
        design: { ...design, version: { ...version, file: fileRow } },
        warnings: prepared.warnings,
      },
      { status: 201 }
    );
  } catch (error) {
    return handleApiError(error, "Designs POST", "Could not create the design.");
  }
}
